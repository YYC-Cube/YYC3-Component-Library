/* ─── 语言包映射 ─── */
const languagePacks: Record<Locale, Record<string, string>> = {
  "zh-CN": zhCN,
  "en-US": enUS,
};

/* ─── Store 接口 ─── */
interface I18nStore {
  locale: Locale;
  translations: Record<string, string>;

  /* 操作 */
  setLocale: (locale: Locale) => void;
  t: (key: TranslationKey, params?: Record<string, string | number>) => string;
  getLocaleInfo: () => LocaleInfo;
}

export const useI18nStore = create<I18nStore>()(
  persist(
    (set, get) => ({
      locale: "zh-CN",
      translations: zhCN,

      setLocale: (locale) => {
        const translations = languagePacks[locale] || zhCN;
        set({ locale, translations });
      },

      t: (key, params) => {
        const translations = get().translations;
        let text = translations[key] || key;
        if (params) {
          Object.entries(params).forEach(([k, v]) => {
            text = text.replace(`{${k}}`, String(v));
          });
        }
        return text;
      },

      getLocaleInfo: () => {
        const locale = get().locale;
        return supportedLocales.find((l) => l.id === locale) || supportedLocales[0];
      },
    }),
    {
      name: "yyc3-i18n",
      partialize: (state) => ({ locale: state.locale }),
      onRehydrate: () => (state) => {
        if (state) {
          state.translations = languagePacks[state.locale] || zhCN;
        }
      },
    }
  )
);

/* ─── 便捷 Hook ─── */
export function useTranslation() {
  const { t, locale, setLocale, getLocaleInfo } = useI18nStore();
  return { t, locale, setLocale, getLocaleInfo };
}